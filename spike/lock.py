"""
Regenerate env.lock and requirements.lock by solving env.yaml and
requirements.txt in the Dockerfile's base image. Every package an input leaves
unpinned can move, so run it when an input changes, and only then:

    python spike/lock.py

env.lock is re-solved only when env.yaml has changed since it was written, so a
requirements.txt edit can't move the conda packages. Delete env.lock to
re-solve it anyway.
"""

import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).parents[1]
MARKER = "=== pip report ==="


def header(source: str) -> str:
    digest = hashlib.sha256((ROOT / source).read_bytes()).hexdigest()
    return f"# Generated by spike/lock.py from {source} (sha256 {digest}). Don't edit.\n"


def base_image() -> str:
    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf8")
    return re.search(r"^FROM --platform=linux/amd64 (\S+) AS base$", dockerfile, re.M)[1]


def main() -> None:
    env_lock = ROOT / "env.lock"
    keep_env_lock = env_lock.exists() and env_lock.read_text(encoding="utf8").startswith(header("env.yaml"))
    solve = f"""set -e
micromamba install -y -q -n base -f /src/{"env.lock" if keep_env_lock else "env.yaml"} >&2
micromamba env export -n base --explicit --md5
echo '{MARKER}'
pip install --dry-run --quiet --report - -r /src/requirements.txt
"""
    solved = subprocess.run(
        ["docker", "run", "--rm", "--platform", "linux/amd64", "-v", f"{ROOT}:/src:ro",
         base_image(), "bash", "-c", solve],
        check=True, stdout=subprocess.PIPE, text=True,
    )
    conda, report = solved.stdout.split(f"{MARKER}\n")
    installs = sorted(json.loads(report)["install"], key=lambda item: item["metadata"]["name"].lower())
    pins = [
        f"{item['metadata']['name']}=={item['metadata']['version']}"
        f" --hash=sha256:{item['download_info']['archive_info']['hashes']['sha256']}"
        for item in installs
    ]

    if not keep_env_lock:
        env_lock.write_text(header("env.yaml") + conda, encoding="utf8")
    (ROOT / "requirements.lock").write_text(header("requirements.txt") + "\n".join(pins) + "\n", encoding="utf8")

    packages = sum(line.startswith("https://") for line in conda.splitlines())
    print(f"{packages} conda packages ({'kept' if keep_env_lock else 'solved'}), {len(pins)} pip packages")


if __name__ == "__main__":
    main()
